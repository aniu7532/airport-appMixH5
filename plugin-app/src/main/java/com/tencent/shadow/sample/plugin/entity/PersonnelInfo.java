package com.tencent.shadow.sample.plugin.entity;

public class PersonnelInfo {
    public String wgs84_lon;
    public String wgs84_lat;
    public String person_name;
    public String data_source;
    public String task_title;
    public String dept_id;
    public String dept_name;
    public String record_time;

    public String getWgs84_lon() {
        return wgs84_lon;
    }

    public void setWgs84_lon(String wgs84_lon) {
        this.wgs84_lon = wgs84_lon;
    }

    public String getWgs84_lat() {
        return wgs84_lat;
    }

    public void setWgs84_lat(String wgs84_lat) {
        this.wgs84_lat = wgs84_lat;
    }

    public String getPerson_name() {
        return person_name;
    }

    public void setPerson_name(String person_name) {
        this.person_name = person_name;
    }

    public String getData_source() {
        return data_source;
    }

    public void setData_source(String data_source) {
        this.data_source = data_source;
    }

    public String getTask_title() {
        return task_title;
    }

    public void setTask_title(String task_title) {
        this.task_title = task_title;
    }

    public String getDept_id() {
        return dept_id;
    }

    public void setDept_id(String dept_id) {
        this.dept_id = dept_id;
    }

    public String getDept_name() {
        return dept_name;
    }

    public void setDept_name(String dept_name) {
        this.dept_name = dept_name;
    }

    public String getRecord_time() {
        return record_time;
    }

    public void setRecord_time(String record_time) {
        this.record_time = record_time;
    }
}

